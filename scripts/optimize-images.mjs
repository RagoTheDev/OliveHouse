/**
 * Olive House image pipeline.
 *
 * Drop original property photographs into ./photos using the descriptive
 * filenames listed in README.md (hero-exterior.jpg, living-room.jpg, ...).
 * Then run `npm run images`.
 *
 * For every source photo this script writes responsive WebP variants to
 * public/images/<name>-<width>.webp, a social-sharing JPEG for the hero,
 * and regenerates src/data/images.generated.ts (dimensions + variants) so
 * components can render <img srcset> with correct aspect ratios and no
 * layout shift.
 */
import { readdir, mkdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC_DIR = path.join(ROOT, "photos");
const OUT_DIR = path.join(ROOT, "public", "images");
const MANIFEST = path.join(ROOT, "src", "data", "images.generated.ts");

const WIDTHS = [480, 768, 1080, 1440, 1920];
const QUALITY = 75;
const EXT = /\.(jpe?g|png|webp|heic|tiff?)$/i;

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const files = (await readdir(SRC_DIR)).filter((f) => EXT.test(f)).sort();
  if (files.length === 0) {
    console.error(`No source photos found in ${SRC_DIR}. See README.md.`);
    process.exit(1);
  }

  const manifest = {};
  for (const file of files) {
    const name = file.replace(EXT, "");
    const input = path.join(SRC_DIR, file);
    const image = sharp(input).rotate(); // honour EXIF orientation
    const meta = await image.metadata();
    const srcW = meta.width ?? 0;
    const srcH = meta.height ?? 0;
    const widths = WIDTHS.filter((w) => w <= srcW);
    if (widths.length === 0 || widths[widths.length - 1] !== srcW) widths.push(Math.min(srcW, 1920));

    const variants = [];
    for (const w of widths) {
      const out = path.join(OUT_DIR, `${name}-${w}.webp`);
      const h = Math.round((srcH / srcW) * w);
      await sharp(input).rotate().resize({ width: w, withoutEnlargement: true }).webp({ quality: QUALITY, effort: 5 }).toFile(out);
      const size = (await stat(out)).size;
      variants.push({ width: w, height: h, src: `/images/${name}-${w}.webp` });
      process.stdout.write(`${name}-${w}.webp  ${(size / 1024).toFixed(0)} KB\n`);
    }

    // Tiny blurred placeholder for progressive reveal (inline data URI).
    const placeholderBuf = await sharp(input).rotate().resize({ width: 24 }).webp({ quality: 40 }).toBuffer();
    const placeholder = `data:image/webp;base64,${placeholderBuf.toString("base64")}`;

    manifest[name] = { width: srcW, height: srcH, variants, placeholder };
  }

  // Social sharing image (1200x630 JPEG) from the hero if present.
  if (manifest["hero-exterior"]) {
    await sharp(path.join(SRC_DIR, files.find((f) => f.startsWith("hero-exterior"))))
      .rotate()
      .resize(1200, 630, { fit: "cover", position: "centre" })
      .jpeg({ quality: 82 })
      .toFile(path.join(OUT_DIR, "og-image.jpg"));
    process.stdout.write("og-image.jpg\n");
  }

  const ts = `// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.
// Run \`npm run images\` after adding or replacing photos in ./photos.

export interface ImageVariant {
  width: number;
  height: number;
  src: string;
}

export interface ImageAsset {
  width: number;
  height: number;
  variants: ImageVariant[];
  placeholder: string;
}

export const images = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageAsset>;

export type ImageKey = keyof typeof images;
`;
  await mkdir(path.dirname(MANIFEST), { recursive: true });
  await writeFile(MANIFEST, ts);
  process.stdout.write(`\nWrote ${path.relative(ROOT, MANIFEST)} with ${files.length} images.\n`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
